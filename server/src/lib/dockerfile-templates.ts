const withEnv = (command: string) => {
  return `RUN --mount=type=secret,id=appenv,target=/run/secrets/appenv sh -c 'set -a; . /run/secrets/appenv; set +a; ${command}'`;
};

const lines = (...items: string[]) => `${items.join("\n")}\n`;

const nodeServer = (cmd: string) => {
  return lines(
    "FROM node:22-alpine",
    "WORKDIR /app",
    "COPY package*.json ./",
    "RUN npm ci",
    "COPY . .",
    withEnv("npm run build --if-present"),
    "ENV NODE_ENV=production PORT=3000",
    "EXPOSE 3000",
    `CMD ${cmd}`,
  );
};

const nodeBuilt = (env: string, copy: string[], cmd: string) => {
  return lines(
    "FROM node:22-alpine AS build",
    "WORKDIR /app",
    "COPY package*.json ./",
    "RUN npm ci",
    "COPY . .",
    withEnv("npm run build"),
    "RUN npm prune --omit=dev",
    "",
    "FROM node:22-alpine",
    "WORKDIR /app",
    `ENV NODE_ENV=production PORT=3000 ${env}`,
    ...copy,
    "EXPOSE 3000",
    `CMD ${cmd}`,
  );
};

const nginxConfig = "RUN printf 'server {\\n  listen 3000;\\n  root /usr/share/nginx/html;\\n  location / {\\n    try_files $uri $uri/ /index.html;\\n  }\\n}\\n' > /etc/nginx/conf.d/default.conf";

const pythonApp = (cmd: string, extra: string[] = []) => {
  return lines(
    "FROM python:3.12-slim",
    "WORKDIR /app",
    "ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PORT=3000",
    "COPY requirements.txt ./",
    "RUN pip install --no-cache-dir -r requirements.txt gunicorn",
    "COPY . .",
    ...extra,
    "EXPOSE 3000",
    `CMD ["sh", "-c", "${cmd}"]`,
  );
};

