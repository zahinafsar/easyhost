
const BUILD_SECRET = "RUN --mount=type=secret,id=appenv,target=/run/secrets/appenv";

export const buildStep = (command) => `${BUILD_SECRET} sh -c 'set -a; . /run/secrets/appenv; set +a; ${command}'`;

export const nodeDockerfile = ({ from = "node:22-alpine", copy = "COPY package*.json ./", install = "RUN npm ci", build = "npm run build --if-present", runDir = "", env = "", cmd = '["npm", "start"]' } = {}) => {
  const lines = [`FROM ${from}`, "WORKDIR /app"];
  if (copy) {
    lines.push(copy, install, "COPY . .");
  } else {
    lines.push("COPY . .", install);
  }
  lines.push(buildStep(build));
  if (runDir) {
    lines.push(`WORKDIR /app/${runDir}`);
  }
  let envLine = "ENV NODE_ENV=production PORT=3000";
  if (env) {
    envLine = `${envLine} ${env}`;
  }
  lines.push(envLine, "EXPOSE 3000", `CMD ${cmd}`);
  return lines.join("\n");
};

